"""
SolarAI - Hardware Streaming Test Utility (Development & Testing Tool)
========================================================================
STRICT TESTING DIRECTIVE:
This script simulates incoming ESP32 edge telemetry for development,
verifying device ONLINE/STALE/OFFLINE status transitions, frontend gauge updates,
and websocket/polling behavior.

All packets generated by this script are explicitly tagged with data_quality='DEMO'.
They are STRICTLY EXCLUDED from AI/ML training datasets in ml/dataset.py
to prevent contamination of real hardware training data.
========================================================================
"""

import sys
import time
import argparse
import random
import urllib.request
import json
from datetime import datetime, timezone


def stream_packets(
    base_url: str = "http://127.0.0.1:8000",
    device_id: str = "SOLAR-ESP32-01",
    count: int = 15,
    interval_sec: float = 2.0,
):
    print("=" * 70)
    print("  SolarAI Hardware Telemetry Streamer (DEV / TESTING ONLY)")
    print(f"  Target Server : {base_url}")
    print(f"  Device ID     : {device_id}")
    print(f"  Packet Count  : {count}")
    print(f"  Interval      : {interval_sec}s")
    print("  Data Tagging  : data_quality='DEMO' (Excluded from ML datasets)")
    print("=" * 70)

    endpoint = f"{base_url.rstrip('/')}/api/v1/telemetry/demo-test?device_id={device_id}"

    success_count = 0
    for i in range(1, count + 1):
        # Generate physically plausible solar telemetry under typical sunlight
        # V: 17.5 - 19.5 V, I: 2.0 - 2.8 A, T: 30 - 36 °C, G: 750 - 900 W/m²
        v = round(18.2 + random.uniform(-0.6, 0.9), 2)
        curr = round(2.3 + random.uniform(-0.3, 0.4), 2)
        temp = round(31.5 + random.uniform(-1.0, 3.5), 1)
        irr = round(810.0 + random.uniform(-40.0, 60.0), 1)

        payload = {
            "device_id": device_id,
            "voltage_v": v,
            "current_a": curr,
            "temperature_c": temp,
            "irradiance_w_m2": irr,
            "firmware_version": "1.0.0-dev-test",
        }

        req = urllib.request.Request(
            endpoint,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=5) as response:
                status_code = response.getcode()
                body = json.loads(response.read().decode("utf-8"))
                power = body.get("data", {}).get("power_w", v * curr)
                quality = body.get("data", {}).get("data_quality", "DEMO")
                print(
                    f"[{i:02d}/{count:02d}] HTTP {status_code} | "
                    f"V: {v:5.2f}V | I: {curr:4.2f}A | P: {power:5.2f}W | "
                    f"T: {temp:4.1f}°C | G: {irr:5.1f}W/m² | Quality: {quality}"
                )
                success_count += 1
        except Exception as exc:
            print(f"[{i:02d}/{count:02d}] FAILED: {exc}")

        if i < count:
            time.sleep(interval_sec)

    print("=" * 70)
    print(f"  Streaming complete: {success_count}/{count} demo packets persisted.")
    print("  VERIFIED: All streamed records tagged as DEMO and isolated from ML models.")
    print("=" * 70)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="SolarAI Hardware Test Streamer")
    parser.add_argument("--url", default="http://127.0.0.1:8000", help="FastAPI backend URL")
    parser.add_argument("--device", default="SOLAR-ESP32-01", help="Device identifier")
    parser.add_argument("--count", type=int, default=15, help="Number of packets to send")
    parser.add_argument("--interval", type=float, default=2.0, help="Interval between packets in seconds")

    args = parser.parse_args()
    stream_packets(
        base_url=args.url,
        device_id=args.device,
        count=args.count,
        interval_sec=args.interval,
    )
